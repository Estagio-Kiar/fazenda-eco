export const produtos: Produto[] = base.map((p, i) => ({
  passo: 1,
  minimo: 1,
  origem: 'Fazenda',
  ...p,
  id: `p${String(i + 1).padStart(3, '0')}`,
  imagens: img(p.slug),
  criadoEm: new Date(Date.UTC(2026, 9, 1 + i)).toISOString(),
}))

const porSlug = (slug: string) => produtos.find((p) => p.slug === slug)!

const item = (slug: string, quantidade: number) => {
  const p = porSlug(slug)
  return { produtoId: p.id, nome: p.nome, quantidade, unidade: p.unidade }
}

